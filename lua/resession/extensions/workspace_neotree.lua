local M = {}
local pending

function M.config()
	vim.api.nvim_create_autocmd("LspAttach", {
		group = vim.api.nvim_create_augroup("WorkspaceSessionSymbols", { clear = true }),
		callback = function(event)
			vim.schedule(function()
				local manager = package.loaded["neo-tree.sources.manager"]
				if not manager then
					return
				end
				for _, tab in ipairs(vim.api.nvim_list_tabpages()) do
					local state = manager.get_state("document_symbols", tab)
					if
						state._workspace_restore_symbols
						and state.lsp_bufnr == event.buf
						and state.winid
						and vim.api.nvim_win_is_valid(state.winid)
						and state.lsp_winid
						and vim.api.nvim_win_is_valid(state.lsp_winid)
						and #vim.lsp.get_clients({ bufnr = event.buf, method = "textDocument/documentSymbol" }) > 0
					then
						state._workspace_restore_symbols = nil
						vim.api.nvim_win_call(state.lsp_winid, function()
							manager.navigate(state)
						end)
					end
				end
			end)
		end,
	})
end

function M.on_save()
	local saved = {}
	local manager = package.loaded["neo-tree.sources.manager"]
	if not manager then
		return saved
	end
	local renderer = require("neo-tree.ui.renderer")
	local command = require("neo-tree.command")
	local current_tab = vim.api.nvim_get_current_tabpage()
	for index, tab in ipairs(vim.api.nvim_list_tabpages()) do
		for _, win in ipairs(vim.api.nvim_tabpage_list_wins(tab)) do
			local buf = vim.api.nvim_win_get_buf(win)
			if vim.bo[buf].filetype == "neo-tree" and vim.api.nvim_win_get_config(win).relative == "" then
				local source = vim.b[buf].neo_tree_source
				local position = vim.b[buf].neo_tree_position
				local state = source and manager.get_state(source, tab, position == "current" and win or nil)
				-- A delayed filesystem refresh can replace the visible buffer after a
				-- source switch. Preserve the last explicitly selected source instead.
				local last = command._last
				if tab == current_tab and last and last.source then
					local selected = manager.get_state(last.source, tab, position == "current" and win or nil)
					if selected.winid == win and selected.tree then
						state = selected
					end
				end
				if state then
					local line = state.bufnr == buf and vim.api.nvim_win_get_cursor(win)[1]
						or (state.position and state.position.lnum)
						or 1
					local node = state.tree and state.tree:get_node(line)
					saved[#saved + 1] = {
						tab = index,
						source = state.name,
						path = state.path,
						position = state.current_position or "left",
						width = vim.api.nvim_win_get_width(win),
						focused = win == vim.api.nvim_get_current_win(),
						selected = node and node:get_id(),
						expanded = state.tree and renderer.get_expanded_nodes(state.tree) or {},
						filtered_visible = state.filtered_items and state.filtered_items.visible,
					}
				end
			end
		end
	end
	return saved
end

function M.on_post_load(data)
	pending = data
end

function M.restore_pending()
	-- Called after resession restores autocmds and completes its final :edit.
	local data = pending or {}
	pending = nil
	if #data == 0 then
		return
	end
	local original_win = vim.api.nvim_get_current_win()
	local focus_win = original_win
	local manager = require("neo-tree.sources.manager")
	local tabs = vim.api.nvim_list_tabpages()
	for _, saved in ipairs(data) do
		local tab = tabs[saved.tab]
		if tab then
			vim.api.nvim_set_current_tabpage(tab)
			local state = manager.get_state(saved.source, tab)
			if saved.source == "filesystem" then
				state.force_open_folders = saved.expanded
				state.explicitly_opened_nodes = {}
				for _, path in ipairs(saved.expanded) do
					state.explicitly_opened_nodes[path] = true
				end
				state.filtered_items.visible = saved.filtered_visible
			end
			local args = { source = saved.source, action = "show", position = saved.position }
			if saved.source == "document_symbols" then
				-- Symbols are regenerated by the language server, not serialized.
				state._workspace_restore_symbols = true
				for _, win in ipairs(vim.api.nvim_tabpage_list_wins(tab)) do
					if vim.api.nvim_buf_get_name(vim.api.nvim_win_get_buf(win)) == saved.path then
						vim.api.nvim_set_current_win(win)
						break
					end
				end
			end
			if saved.source == "filesystem" then
				args.dir = vim.fn.isdirectory(saved.path or "") == 1 and saved.path or vim.fn.getcwd()
				if saved.selected and vim.uv.fs_stat(saved.selected) then
					args.reveal_file = saved.selected
				end
			end
			require("neo-tree.command").execute(args)
			if state.winid and vim.api.nvim_win_is_valid(state.winid) then
				vim.api.nvim_win_set_width(state.winid, saved.width)
				if saved.focused then
					focus_win = state.winid
				end
			end
		end
	end
	if vim.api.nvim_win_is_valid(focus_win) then
		vim.api.nvim_set_current_win(focus_win)
	end
end

return M
